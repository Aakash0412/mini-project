if st.button("Generate Recommendation", type="primary", width="stretch"):
    try:
        with st.spinner("Running the trained pricing models..."):
            # Predict sales growth for every paper-defined discount.
            predictions = simulator.predict_all_discounts(state)

            # Deterministic PPO action: highest policy probability.
            state_tensor = torch.as_tensor(
                state, dtype=torch.float32
            ).unsqueeze(0)

            with torch.no_grad():
                distribution = agent.actor.get_distribution(state_tensor)
                probabilities = distribution.probs.squeeze(0).cpu().numpy()
                action = int(np.argmax(probabilities))
                critic_value = float(agent.critic(state_tensor).item())

            recommended_discount = SUPPORTED_DISCOUNTS[action]
            recommended_growth = predictions[recommended_discount]

            if not np.isfinite(probabilities).all():
                raise ValueError("PPO returned non-finite action probabilities.")

            if not np.isclose(probabilities.sum(), 1.0, atol=1e-5):
                raise ValueError("PPO action probabilities do not sum to one.")

            # Calculate prices only when the observed price and discount
            # support a valid reference-price calculation.
            reference_price = None
            recommended_price = None

            if (
                pd.notna(current_price)
                and pd.notna(current_discount)
                and current_price > 0
                and 0 <= current_discount < 100
            ):
                reference_price = current_price / (
                    1.0 - float(current_discount) / 100.0
                )
                recommended_price = reference_price * (
                    1.0 - recommended_discount / 100.0
                )

            st.session_state["pricing_result"] = {
                "selected_row": selected_row,
                "predictions": predictions,
                "probabilities": probabilities,
                "recommended_discount": recommended_discount,
                "recommended_growth": recommended_growth,
                "critic_value": critic_value,
                "reference_price": reference_price,
                "recommended_price": recommended_price,
                "current_price": (
                    float(current_price) if pd.notna(current_price) else None
                ),
                "current_discount": (
                    float(current_discount)
                    if pd.notna(current_discount)
                    else None
                ),
            }

    except Exception as exc:
        st.error(f"Inference failed: {exc}")
        st.exception(exc)


